#!/usr/bin/env python3
# Writes WgpuInterop's StandInMetrics.cs: the metrics of a Windows face the stack stands in for with an
# open font's glyphs (StandInFaces). Only numbers are taken from the Windows face -- each character's
# advance, its hinted widths at the sizes GDI looks up ('hdmx'), the line metrics and 'VDMX' -- never its
# outlines. At run time they are laid over the open font's glyphs, in memory, where the system has no
# face of that name.
#
#   eng/fonts/standin-metrics.py <micross.ttf>
#
# Microsoft Sans Serif ships with Windows (C:\Windows\Fonts\micross.ttf) and with macOS
# (/System/Library/Fonts/Supplemental/Microsoft Sans Serif.ttf).
import base64, os, struct, sys, zlib

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "src", "Microsoft.DotNet.Wpf", "src", "WgpuInterop", "Composition", "Text", "StandInMetrics.cs")

def tables(d):
    n = struct.unpack(">H", d[4:6])[0]
    t = {}
    for i in range(n):
        tag, _, off, ln = struct.unpack(">4sIII", d[12 + 16 * i:28 + 16 * i])
        t[tag.decode("latin1")] = d[off:off + ln]
    return t

def cmap(t):
    c = t["cmap"]; n = struct.unpack(">H", c[2:4])[0]; best = None
    for i in range(n):
        plat, enc, off = struct.unpack(">HHI", c[4 + 8 * i:12 + 8 * i])
        fmt = struct.unpack(">H", c[off:off + 2])[0]
        if plat == 3 and enc in (1, 10) and fmt in (4, 12) and (best is None or fmt == 12): best = (off, fmt)
    off, fmt = best; m = {}
    if fmt == 4:
        segx2 = struct.unpack(">H", c[off + 6:off + 8])[0]; seg = segx2 // 2
        ends = off + 14; starts = ends + segx2 + 2; deltas = starts + segx2; ranges = deltas + segx2
        for s in range(seg):
            end = struct.unpack(">H", c[ends + 2 * s:ends + 2 * s + 2])[0]; start = struct.unpack(">H", c[starts + 2 * s:starts + 2 * s + 2])[0]
            delta = struct.unpack(">h", c[deltas + 2 * s:deltas + 2 * s + 2])[0]; ro = struct.unpack(">H", c[ranges + 2 * s:ranges + 2 * s + 2])[0]
            for cp in range(start, end + 1):
                if cp == 0xFFFF: continue
                if ro == 0: g = (cp + delta) & 0xFFFF
                else:
                    p = ranges + 2 * s + ro + 2 * (cp - start); g = struct.unpack(">H", c[p:p + 2])[0]
                    if g: g = (g + delta) & 0xFFFF
                if g: m[cp] = g
    else:
        ng = struct.unpack(">I", c[off + 12:off + 16])[0]
        for k in range(ng):
            a, b, g = struct.unpack(">III", c[off + 16 + 12 * k:off + 28 + 12 * k])
            for cp in range(a, b + 1): m[cp] = g + cp - a
    return m

src = open(sys.argv[1], "rb").read(); t = tables(src)
upm = struct.unpack(">H", t["head"][18:20])[0]
nhm = struct.unpack(">H", t["hhea"][34:36])[0]
def adv(g): return struct.unpack(">H", t["hmtx"][4 * min(g, nhm - 1):4 * min(g, nhm - 1) + 2])[0]
cm = cmap(t); cps = sorted(cm)
hd = t["hdmx"]; recs, size = struct.unpack(">hI", hd[2:8])
ppems = [hd[8 + size * r] for r in range(recs)]
blob = bytearray(b"WSI1")
blob += struct.pack("<H", upm)
blob += struct.pack("<I", len(cps)) + b"".join(struct.pack("<I", cp) for cp in cps) + b"".join(struct.pack("<H", adv(cm[cp])) for cp in cps)
blob += struct.pack("<B", recs) + bytes(ppems)
for r in range(recs):
    row = hd[8 + size * r + 2:8 + size * r + size]
    blob += bytes(row[cm[cp]] for cp in cps)
hh = t["hhea"]; blob += hh[4:12]                                  # ascender, descender, lineGap, advanceWidthMax (big-endian, as in the table)
os2 = t["OS/2"]; blob += os2[2:4] + os2[32:58] + os2[68:78] + (os2[78:86] if len(os2) >= 86 else bytes(8))   # xAvgCharWidth, panose + unicode ranges, typo/win metrics, code pages
vd = t["VDMX"]; blob += struct.pack("<I", len(vd)) + vd
packed = base64.b64encode(zlib.compress(bytes(blob), 9)).decode()
with open(OUT, "w", newline="\n") as f:
    f.write(f"""// Generated by eng/fonts/standin-metrics.py; do not edit.
//
// Microsoft Sans Serif's metrics -- the advance of each of its {len(cps)} characters, its hinted widths at
// {recs} sizes ('hdmx'), its line metrics and 'VDMX' -- for the face StandInFaces builds over Liberation Sans'
// glyphs where no Microsoft Sans Serif is installed. Numbers only, deflated; no outlines.

namespace Microsoft.Wpf.Interop.WebGpu.Composition.Text
{{
    internal static class StandInMetrics
    {{
        internal const string MicrosoftSansSerif =
""")
    for i in range(0, len(packed), 120):
        f.write(f"            \"{packed[i:i + 120]}\"" + (" +\n" if i + 120 < len(packed) else ";\n"))
    f.write("    }\n}\n")
print(f"standin-metrics: {len(cps)} characters, {recs} hdmx sizes, {len(blob)} bytes -> {len(packed)} base64 -> {OUT}")
