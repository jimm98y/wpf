#!/usr/bin/env python3
# Writes WgpuInterop's StandInVdmx.cs: for each Selawik face the stack ships, the 'VDMX' table of the
# Segoe UI face it stands in for -- the per-size line extents GDI and DirectWrite's GDI-compatible
# metrics take on Windows. Only those numbers are taken from Segoe UI; no glyphs, and the Selawik files
# stay as published (their licence reserves the name for unmodified fonts).
#
#   eng/fonts/standin-vdmx.py <folder with segoeui*.ttf>
#
# Segoe UI ships with Windows (C:\Windows\Fonts) and with Microsoft's Windows App for macOS.
import os, struct, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FONTS = os.path.join(ROOT, "sdk", "WpfWebGpu.Fonts", "fonts")
OUT = os.path.join(ROOT, "src", "Microsoft.DotNet.Wpf", "src", "WgpuInterop", "Composition", "Text", "StandInVdmx.cs")
PAIRS = [("Selawik-Light.ttf", "segoeuil.ttf"), ("Selawik-Semilight.ttf", "segoeuisl.ttf"), ("Selawik-Regular.ttf", "segoeui.ttf"),
         ("Selawik-Semibold.ttf", "seguisb.ttf"), ("Selawik-Bold.ttf", "segoeuib.ttf")]
# The dropout control each Segoe UI face's 'prep' turns on (SCANCTRL / SCANTYPE), as the renderer's value
# (scan type + 1), the same at every size: read with the stack's own interpreter
# (TrueTypeFont.DWriteUnfittedDropout). Selawik has no 'prep', so no dropout control, and the thin
# horizontal strokes of a nine-point title fell between pixel rows and vanished (a G and an E unreadable).
DROPOUT = {"segoeui.ttf": 2, "segoeuil.ttf": 6, "segoeuisl.ttf": 6}

def tables(path):
    d = open(path, "rb").read()
    n = struct.unpack(">H", d[4:6])[0]
    t = {}
    for i in range(n):
        tag, _, off, ln = struct.unpack(">4sIII", d[12 + 16 * i:28 + 16 * i])
        t[tag.decode("latin1")] = d[off:off + ln]
    return t

source = sys.argv[1]
rows = []
for selawik, segoe in PAIRS:
    path = os.path.join(source, segoe)
    if not os.path.exists(path):
        print(f"standin-vdmx: {segoe} not in {source}: {selawik} keeps its rounded Windows metrics")
        continue
    key = struct.unpack(">I", tables(os.path.join(FONTS, selawik))["head"][8:12])[0]
    vdmx = tables(path)["VDMX"]
    rows.append((selawik, segoe, key, vdmx, DROPOUT.get(segoe, 0)))
    print(f"standin-vdmx: {selawik} <- {segoe} ({len(vdmx)} bytes)")

with open(OUT, "w", newline="\n") as f:
    f.write("""// Generated by eng/fonts/standin-vdmx.py; do not edit.
//
// The 'VDMX' tables of the Segoe UI faces the stack's Selawik stands in for. Selawik matches Segoe UI's
// advances and its Windows ascent and descent, but carries no VDMX, and VDMX is where GDI and
// DirectWrite's GDI-compatible metrics (WPF's Display text) take a face's line box at each size on
// Windows: Segoe UI at 12ppem is 12 up and 3 down, 15 pixels, where the rounded Windows metrics make 16.
// Every GDI line of a 9-point Segoe UI was a pixel tall at 96 dpi, and a ribbon's three rows of small
// buttons outgrew their group and were cut off at the top. A face is known by its 'head'
// checkSumAdjustment, which differs for every file.

namespace Microsoft.Wpf.Interop.WebGpu.Composition.Text
{
    internal static class StandInVdmx
    {
        /// <summary>The VDMX table for a face that has none of its own, by its 'head' checkSumAdjustment;
        /// null for any face the stack does not stand in with.</summary>
        internal static byte[]? For(uint checkSumAdjustment) => checkSumAdjustment switch
        {
""")
    for selawik, segoe, key, vdmx, _ in rows:
        f.write(f"            0x{key:08X} => {selawik.replace('-', '').replace('.ttf', '')},   // {selawik}: {segoe}\n")
    f.write("            _ => null,\n        };\n")
    f.write("""
        /// <summary>The dropout control the face's Segoe UI turns on in its 'prep', as the renderer's value
        /// (scan type + 1), by the stand-in's 'head' checkSumAdjustment; 0 for any other face.</summary>
        internal static int Dropout(uint checkSumAdjustment) => checkSumAdjustment switch
        {
""")
    for selawik, segoe, key, vdmx, drop in rows:
        if drop: f.write(f"            0x{key:08X} => {drop},   // {selawik}: {segoe}\n")
    f.write("            _ => 0,\n        };\n")
    for selawik, segoe, key, vdmx, _ in rows:
        name = selawik.replace('-', '').replace('.ttf', '')
        f.write(f"\n        private static readonly byte[] {name} = System.Convert.FromHexString(\n")
        h = vdmx.hex().upper()
        for i in range(0, len(h), 128):
            f.write(f"            \"{h[i:i + 128]}\"" + (" +\n" if i + 128 < len(h) else ");\n"))
    f.write("    }\n}\n")
print(f"standin-vdmx: wrote {OUT}")
