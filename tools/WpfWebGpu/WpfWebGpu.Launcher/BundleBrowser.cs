// The browser head's template (wpfrun pack --browser): the page with no app in it, which the Packager fills without a
// build -- the app's folder mounted at the page's file system root (payload/, which the page mounts before it starts),
// its name in /wpfrun-app.txt, its assemblies loaded from there when the runtime asks for them, as the iOS template's
// host loads them from its app/ folder.
//
// Everything the stack and the runtime have is kept (nothing trimmed): the template does not know which app it will
// start, and an app reaches its parts by name, as on Windows. Its assemblies stay plain .dll files (no webcil), the
// same files the Packager rewrites an app's against.

using System.Text;

namespace WpfWebGpu;

internal static partial class Bundle
{
    internal static void WriteBrowserTemplateProject(string dir, string feed)
    {
        File.WriteAllText(Path.Combine(dir, "Bundle.csproj"), """
            <!-- Generated by wpfrun pack (the browser template): the Packager's template; regenerated on every run. -->
            <Project Sdk="WpfWebGpu.Sdk/0.1.1">

              <PropertyGroup>
                <OutputType>Exe</OutputType>
                <TargetFramework>net10.0</TargetFramework>
                <UseWPF>true</UseWPF>
                <UseWindowsForms>true</UseWindowsForms>
                <AssemblyName>WpfRunBundle</AssemblyName>
                <Nullable>disable</Nullable>
                <ImplicitUsings>disable</ImplicitUsings>
                <EnableNETAnalyzers>false</EnableNETAnalyzers>
                <AnalysisLevel>none</AnalysisLevel>
                <EnforceCodeStyleInBuild>false</EnforceCodeStyleInBuild>
                <WpfWebGpuAot>false</WpfWebGpuAot>
                <!-- nothing trimmed: the app is not known yet, and it reaches its parts by name -->
                <PublishTrimmed>false</PublishTrimmed>
                <!-- plain assemblies: the Packager rewrites an app's against these very files -->
                <WasmEnableWebcil>false</WasmEnableWebcil>
                <!-- an app's threads are threads (Web Workers): the page is served cross-origin isolated (COOP/COEP) -->
                <WasmEnableThreads>true</WasmEnableThreads>
                <MSBuildWarningsAsMessages>$(MSBuildWarningsAsMessages);MSB3277;MSB3243;MSB3245</MSBuildWarningsAsMessages>
              </PropertyGroup>

            </Project>
            """);
        File.WriteAllText(Path.Combine(dir, "Program.cs"), """
            // Generated by wpfrun pack --browser: the template's host, which starts the app the page holds.
            using System;
            using System.Collections.Generic;
            using System.IO;
            using System.Reflection;
            using System.Runtime.Loader;

            internal static class WpfRunBundleHost
            {
                [STAThread]
                private static int Main(string[] args)
                {
                    // the app this page starts (wpfrun-app.txt, mounted with the app's folder at the root by the page)
                    var info = new Dictionary<string, string> { ["name"] = "", ["exe"] = "", ["osidentity"] = "" };
                    if (File.Exists("/wpfrun-app.txt"))
                        foreach (string line in File.ReadAllLines("/wpfrun-app.txt"))
                        {
                            int eq = line.IndexOf('=');
                            if (eq > 0) info[line[..eq]] = line[(eq + 1)..];
                        }
                    string name = info["name"];
                    if (name.Length == 0) throw new InvalidOperationException("this page holds no app (a template the Packager has not filled)");

                    // its assemblies, from its folder, as the runtime asks for them (its satellites from their cultures')
                    AssemblyLoadContext.Default.Resolving += (context, wanted) =>
                    {
                        string file = string.IsNullOrEmpty(wanted.CultureName) || wanted.CultureName == "neutral"
                            ? "/" + wanted.Name + ".dll" : "/" + wanted.CultureName + "/" + wanted.Name + ".dll";
                        if (!File.Exists(file)) return null;
                        using var stream = File.OpenRead(file);
                        return context.LoadFromStream(stream);
                    };

                    // the app's configuration, not this host's: what ConfigurationManager reads
                    AppContext.SetData("APP_CONFIG_FILE", "/" + name + ".dll.config");
                    // the file the app is started from, first on its command line as on Windows (BrowserApis)
                    AppContext.SetData("WPFWEBGPU_APP_PATH", "/" + (info["exe"].Length > 0 ? info["exe"] : name + ".exe"));
                    // the machine's state the page carries: ProgramData and the like under /state, the registry under
                    // /registry (Windows' machine-wide folders, WindowsPaths)
                    AppContext.SetData("WPFWEBGPU_STATE_DIR", "/state");
                    Environment.SetEnvironmentVariable("WPFWEBGPU_REGISTRY_DIR", "/registry");
                    // a product written for Windows only, told it runs on it (WindowsPaths: WPFWEBGPU_OS_IDENTITY)
                    if (info["osidentity"].Length > 0) Environment.SetEnvironmentVariable("WPFWEBGPU_OS_IDENTITY", info["osidentity"]);

                    Assembly app = Assembly.Load(new AssemblyName(name));
                    // the app is the process's entry assembly, as when its own .exe starts it
                    Assembly.SetEntryAssembly(app);
                    MethodInfo entry = app.EntryPoint ?? throw new InvalidOperationException(name + " has no entry point");
                    object result = entry.Invoke(null, entry.GetParameters().Length == 1 ? new object[] { args } : null);
                    return result is int code ? code : 0;
                }
            }
            """);
        File.WriteAllText(Path.Combine(dir, "nuget.config"), $"""
            <?xml version="1.0" encoding="utf-8"?>
            <configuration>
              <packageSources>
                <clear />
                <add key="wpfwebgpu" value="{Xml(feed)}" />
                <add key="nuget.org" value="https://api.nuget.org/v3/index.json" />
              </packageSources>
            </configuration>
            """);
        File.WriteAllText(Path.Combine(dir, "Directory.Build.props"), "<Project />\n");
        File.WriteAllText(Path.Combine(dir, "Directory.Build.targets"), "<Project />\n");
    }
}
