// Writes AppHostInterfaces.g.cs from the interfaces Microsoft.Web.Administration declares for IIS's configuration system:
// each one standalone (its base's slots redeclared, as tlbimp lays them out), its members in vtable order, property
// accessors as the methods they are, with their marshalling.

using System.Reflection;
using System.Text;
using Mono.Cecil;

string Meta(string key) => typeof(Program).Assembly.GetCustomAttributes<AssemblyMetadataAttribute>().First(a => a.Key == key).Value!;
var m = ModuleDefinition.ReadModule(Meta("MicrosoftWebAdministration"));
var sb = new StringBuilder();
sb.Append("""
// <auto-generated/>
// IIS's configuration interfaces (ahadmin: AppHostAdminLibrary), as their clients bind to them -- Microsoft.Web.Administration
// among them: each interface's IID and its vtable, slot by slot (IUnknown's, then these in order; a property's accessors are
// its slots, as methods here; an interface's base's slots redeclared in it, as tlbimp lays them out, so each stands alone).
// Generated from the interfaces Microsoft.Web.Administration 11.1.0 declares (GenInterfaces/ in this folder).

using System.Runtime.InteropServices;

namespace WpfWebGpu.IisAdmin;

#pragma warning disable CS0108


""");
string Mi(MarshalInfo? i) => i switch
{
    null => "",
    SafeArrayMarshalInfo s => $"[MarshalAs(UnmanagedType.SafeArray, SafeArraySubType = VarEnum.VT_{s.ElementType.ToString().ToUpperInvariant()})] ",
    _ => $"[MarshalAs(UnmanagedType.{i.NativeType switch { NativeType.BStr => "BStr", NativeType.IntF => "Interface", NativeType.IUnknown => "IUnknown", NativeType.Struct => "Struct", NativeType.Boolean => "Bool", NativeType.VariantBool => "VariantBool", var n => n.ToString() }})] ",
};
string T(TypeReference t) => t.FullName switch
{
    "System.Void" => "void", "System.Boolean" => "bool", "System.Int32" => "int", "System.UInt32" => "uint", "System.IntPtr" => "IntPtr",
    "System.Object" => "object", "System.Object[]" => "object[]", "System.String" => "string",
    _ when t.IsByReference => T(((ByReferenceType)t).ElementType),
    _ => t.Name,
};
foreach (var t in m.Types.Where(t => t.Namespace == "Microsoft.Web.Administration.Interop" && t.IsInterface).OrderBy(t => t.Name, StringComparer.Ordinal))
{
    string guid = (string)t.CustomAttributes.First(a => a.AttributeType.Name == "GuidAttribute").ConstructorArguments[0].Value;
    sb.Append($"[ComImport, Guid(\"{guid.ToUpperInvariant()}\"), InterfaceType(ComInterfaceType.InterfaceIsIUnknown)]\n");
    sb.Append($"public interface {t.Name}\n{{\n");
    foreach (var md in t.Methods)
    {
        var ps = md.Parameters.Select(p =>
        {
            string dir = p.IsOut && p.ParameterType.IsByReference ? "out " : p.ParameterType.IsByReference ? "ref " : "";
            string attrs = (p.IsIn && !p.IsOut ? "[In] " : "") + Mi(p.MarshalInfo);
            return $"{attrs}{dir}{T(p.ParameterType)} {(p.Name.Length > 0 ? p.Name : "value")}";
        });
        string ret = md.MethodReturnType.HasMarshalInfo ? "    [return: " + Mi(md.MethodReturnType.MarshalInfo).Trim().TrimStart('[').TrimEnd(']') + "]\n" : "";
        sb.Append(ret).Append($"    {T(md.ReturnType)} {md.Name}({string.Join(", ", ps)});\n");
    }
    sb.Append("}\n\n");
}
File.WriteAllText(Meta("Output"), sb.ToString().TrimEnd() + "\n");
Console.WriteLine("wrote " + Meta("Output"));

