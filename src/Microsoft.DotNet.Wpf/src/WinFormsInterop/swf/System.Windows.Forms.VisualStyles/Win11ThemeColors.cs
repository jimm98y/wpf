		/// <summary>uxtheme's inheritance: the part and state, the part, the class, then GLOBALS.</summary>
		internal static bool TryGet (string cls, int part, int state, int prop, out Color color)
		{
			if (cls != null && (s_colors.TryGetValue ((cls, part, state, prop), out int rgb)
			    || s_colors.TryGetValue ((cls, part, 0, prop), out rgb)
			    || s_colors.TryGetValue ((cls, 0, 0, prop), out rgb)
			    || s_colors.TryGetValue (("GLOBALS", 0, 0, prop), out rgb))) {
				color = Color.FromArgb ((rgb >> 16) & 0xff, (rgb >> 8) & 0xff, rgb & 0xff);
				return true;
			}
			color = Color.Empty;
			return false;
		}
