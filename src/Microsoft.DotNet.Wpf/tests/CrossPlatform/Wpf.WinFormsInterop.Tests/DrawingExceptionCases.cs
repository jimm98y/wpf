        // ---------------------------------------------------------------------------------------
        // Outcome: one tab-separated line, the same shape for both runs.
        //   OK <tab> value
        //   <exception type> <tab> message <tab> ParamName <tab> HRESULT (ExternalException only)
        // ---------------------------------------------------------------------------------------
        internal static string Outcome(Case c)
        {
            object r;
            try
            {
                r = c.Run();
            }
            catch (Exception e)
            {
                while (e is TargetInvocationException && e.InnerException != null)
                    e = e.InnerException;
                if (e is SetupException)
                {
                    Exception i = e.InnerException;
                    return "SETUP\t" + Clean(e.Message + ": " + i?.GetType().FullName + ": " + i?.Message);
                }
                string line = e.GetType().FullName + "\t" + Clean(e.Message) + "\t" + ((e as ArgumentException)?.ParamName ?? "");
                if (e is ExternalException x)
                    line += "\t0x" + x.ErrorCode.ToString("X8", CultureInfo.InvariantCulture);
                return line;
            }
            string v;
            try { v = Describe(r); } catch (Exception e) { v = "<describe: " + e.GetType().Name + ">"; }
            return "OK\t" + Clean(v);
        }

        internal static string Clean(string s)
        {
            if (s == null) return "";
            string t = Path.GetTempPath();
            s = s.Replace(TempDir, "<TMP>").Replace(t.TrimEnd('\\', '/'), "<TEMP>");
            // the oracle was recorded on Windows: a path under the temporary folder in its separators
            if (!OperatingSystem.IsWindows()) s = WindowsSeparators(s);
            return s.Replace("\r\n", "\\n").Replace("\n", "\\n").Replace("\r", "\\n").Replace("\t", "\\t");
        }

        // each '/' of a path that starts at <TMP> or <TEMP>, up to the next space or quote, as '\\'
        private static string WindowsSeparators(string s)
        {
            var sb = new System.Text.StringBuilder(s);
            foreach (string mark in new[] { "<TMP>", "<TEMP>" })
                for (int at = s.IndexOf(mark, StringComparison.Ordinal); at >= 0; at = s.IndexOf(mark, at + 1, StringComparison.Ordinal))
                    for (int i = at + mark.Length; i < s.Length && !char.IsWhiteSpace(s[i]) && s[i] != '\'' && s[i] != '"'; i++)
                        if (s[i] == '/') sb[i] = '\\';
            return sb.ToString();
        }

        internal static string Describe(object r, int depth = 0)
        {
            switch (r)
            {
                case null: return "null";
                case string s: return "\"" + s + "\"";
                case IntPtr p: return p == IntPtr.Zero ? "0" : "nz";
                case float f: return f.ToString("R", CultureInfo.InvariantCulture);
                case double d: return d.ToString("R", CultureInfo.InvariantCulture);
                case bool b: return b ? "true" : "false";
                case Enum e: return e.ToString();
                case Image im:
                    try { return im.GetType().Name + " " + im.Width + "x" + im.Height + " " + im.PixelFormat; }
                    catch (Exception e) { return im.GetType().Name + " <" + e.GetType().Name + ">"; }
                case Icon ic:
                    try { return "Icon " + ic.Width + "x" + ic.Height; }
                    catch (Exception e) { return "Icon <" + e.GetType().Name + ">"; }
                case Color c: return c.ToString();
                case Point or PointF or Size or SizeF or Rectangle or RectangleF or CharacterRange or Guid:
                    return Convert.ToString(r, CultureInfo.InvariantCulture);
                case IFormattable fm when r.GetType().IsPrimitive || r is decimal:
                    return fm.ToString(null, CultureInfo.InvariantCulture);
                case Array a:
                {
                    var sb = new StringBuilder(a.GetType().GetElementType().Name + "[" + a.Length + "]");
                    if (depth < 2)
                    {
                        sb.Append('{');
                        int n = 0;
                        foreach (object o in a)
                        {
                            if (n++ == 16) { sb.Append(",..."); break; }
                            if (n > 1) sb.Append(',');
                            sb.Append(Describe(o, depth + 1));
                        }
                        sb.Append('}');
                    }
                    return sb.ToString();
                }
            }
            return r.GetType().Name;
        }

