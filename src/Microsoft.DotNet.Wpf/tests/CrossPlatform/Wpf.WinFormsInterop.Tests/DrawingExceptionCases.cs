        private static List<Case> Build()
        {
            var list = new List<Case>();
            foreach (Type t in s_types)
                AddReflected(list, t);
            AddHandWritten(list);
            var seen = new HashSet<string>();
            var unique = new List<Case>();
            foreach (Case c in list)
                if (seen.Add(c.Name)) unique.Add(c);
            unique.Sort((a, b) => string.CompareOrdinal(a.Name, b.Name));
            return unique;
        }

        private static void AddReflected(List<Case> list, Type t)
        {
            const BindingFlags inst = BindingFlags.Public | BindingFlags.Instance;
            const BindingFlags stat = BindingFlags.Public | BindingFlags.Static | BindingFlags.DeclaredOnly;
            bool canMake = s_receivers.ContainsKey(t);

            if (!t.IsAbstract)
            {
                foreach (ConstructorInfo ci in t.GetConstructors(inst))
                    if (Invokable(ci) && !s_skip.Contains(t.Name + ".ctor"))
                        AddVariants(list, t, ci, null);
            }
            foreach (MethodInfo mi in t.GetMethods(stat))
            {
                if (!Invokable(mi) || mi.Name.StartsWith("op_", StringComparison.Ordinal) || s_skip.Contains(t.Name + "." + mi.Name)) continue;
                if (mi.IsSpecialName && !mi.Name.StartsWith("get_", StringComparison.Ordinal)) continue;
                AddVariants(list, t, mi, null);
            }

            if (!canMake) return;
            foreach (MethodInfo mi in t.GetMethods(inst))
            {
                Type decl = mi.DeclaringType;
                if (decl == typeof(object) || decl == typeof(MarshalByRefObject) || decl.Assembly != t.Assembly && decl != t) continue;
                if (mi.Name is "Dispose" or "GetHashCode" or "GetType" or "Finalize" or "GetLifetimeService" or "InitializeLifetimeService" or "CreateObjRef") continue;
                if (mi.IsSpecialName && !(mi.Name.StartsWith("get_", StringComparison.Ordinal) || mi.Name.StartsWith("set_", StringComparison.Ordinal))) continue;
                if (!Invokable(mi) || s_skip.Contains(t.Name + "." + mi.Name) || s_skip.Contains(decl.Name + "." + mi.Name)) continue;
                AddVariants(list, t, mi, s_receivers[t]);
            }
        }

        private static void AddVariants(List<Case> list, Type t, MethodBase m, Func<object> make)
        {
            string baseName = t.Name + "." + Sig(m);
            ParameterInfo[] ps = m.GetParameters();
            bool vol = VolatileType(t) || AnyOf(m.Name, s_volatileMember, StringComparison.Ordinal);

            void Add(string variant, Func<object> receiver, int pIndex, Func<ParameterInfo, object> pValue)
            {
                list.Add(new Case
                {
                    Name = baseName + "|" + variant,
                    VolatileResult = vol,
                    Run = () =>
                    {
                        object target = null;
                        if (receiver != null)
                        {
                            try { target = receiver(); }
                            catch (Exception e) { throw new SetupException("receiver", e); }
                        }
                        var args = new object[ps.Length];
                        for (int i = 0; i < ps.Length; i++)
                        {
                            try { args[i] = i == pIndex ? pValue(ps[i]) : Arg(ps[i].ParameterType, ps[i].Name, m.Name); }
                            catch (Exception e) { throw new SetupException("arg " + i, e); }
                        }
                        return m is ConstructorInfo ci ? ci.Invoke(args) : m.Invoke(target, args);
                    },
                });
            }

            Func<object> live = make;
            Add("ok", live, -1, null);
            for (int i = 0; i < ps.Length; i++)
            {
                Type pt = ps[i].ParameterType.IsByRef ? ps[i].ParameterType.GetElementType() : ps[i].ParameterType;
                if (ps[i].IsOut) continue;
                if (!pt.IsValueType)
                    Add("null:" + i, live, i, _ => null);
                if (Disposable(pt))
                {
                    Type pt2 = pt;
                    string pn = ps[i].Name;
                    Add("disp:" + i, live, i, p =>
                    {
                        object o = Arg(pt2, pn, m.Name);
                        ((IDisposable)o)?.Dispose();
                        return o;
                    });
                }
                if ((pt == typeof(int) || pt == typeof(float) || pt == typeof(long) || pt == typeof(double)) && AnyOf(ps[i].Name ?? "", s_sizeLike, StringComparison.OrdinalIgnoreCase))
                {
                    Type pt2 = pt;
                    Add("neg:" + i, live, i, _ => Convert.ChangeType(-1, pt2, CultureInfo.InvariantCulture));
                }
            }
            if (make != null && typeof(IDisposable).IsAssignableFrom(t))
            {
                Func<object> disposed = () =>
                {
                    object o = make();
                    ((IDisposable)o).Dispose();
                    return o;
                };
                Add("disposed", disposed, -1, null);
                // Which comes first: System.Drawing's own argument checks or GDI+'s of the handle.
                for (int i = 0; i < ps.Length; i++)
                {
                    Type pt = ps[i].ParameterType.IsByRef ? ps[i].ParameterType.GetElementType() : ps[i].ParameterType;
                    if (!ps[i].IsOut && !pt.IsValueType)
                        Add("dnull:" + i, disposed, i, _ => null);
                }
            }
            if (make != null && t == typeof(Graphics))
            {
                Add("hdc", () =>
                {
                    var g = (Graphics)make();
                    g.GetHdc();
                    return g;
                }, -1, null);
            }
            if (make != null && t == typeof(Bitmap))
            {
                Add("locked", () =>
                {
                    var b = (Bitmap)make();
                    b.LockBits(new Rectangle(0, 0, b.Width, b.Height), ImageLockMode.ReadWrite, b.PixelFormat);
                    return b;
                }, -1, null);
            }
        }

        private static void H(List<Case> list, string name, Func<object> run, bool vol = false) =>
            list.Add(new Case { Name = "~" + name, Run = run, VolatileResult = vol });

        private static void H(List<Case> list, string name, Action run) =>
            list.Add(new Case { Name = "~" + name, Run = () => { run(); return null; } });
    }
