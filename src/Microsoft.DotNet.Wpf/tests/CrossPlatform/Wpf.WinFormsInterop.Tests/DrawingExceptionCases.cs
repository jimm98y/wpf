// The case library behind DrawingExceptionParityTests: what every public System.Drawing member does
// with a valid call, an invalid argument, a disposed receiver or argument, and a busy receiver.
//
// The same file is compiled twice outside this suite, into a stock recorder (net10.0-windows,
// System.Drawing.Common on native GDI+) and into a recorder over the fork's System.Drawing, so the
// two runs enumerate the same cases under the same names. The stock run's outcomes are the checked-in
// oracle (Fixtures/Drawing/exceptions.stock.txt); see DrawingExceptionParityTests for how to
// regenerate it.
//
// Most cases are generated by reflection over an explicit type list: for every public constructor,
// method and property accessor, the call is made with synthesized valid arguments ("ok"), then with
// each reference argument null ("null:N"), each disposable argument disposed ("disp:N"), each
// size-like number negative ("neg:N"), and on a disposed receiver ("disposed"). Graphics also runs
// every member while its HDC is out ("hdc") and Bitmap while its bits are locked ("locked"). The
// hand-written cases below cover what reflection cannot reach (states built up over several calls,
// specific bad data).
//
// Keep this file compiling against both System.Drawing.Common and the fork's System.Drawing: name
// only API both have, and add a member to the skip list rather than an #if.

