        private static string Sig(MethodBase m)
        {
            var sb = new StringBuilder(m is ConstructorInfo ? ".ctor" : m.Name).Append('(');
            ParameterInfo[] ps = m.GetParameters();
            for (int i = 0; i < ps.Length; i++)
            {
                if (i > 0) sb.Append(',');
                sb.Append(ps[i].ParameterType.Name);
            }
            return sb.Append(')').ToString();
        }

        // API the fork does not have: .NET 8's image effects and cached bitmaps (GDI+ 1.1 objects with
        // no managed implementation) and the shell's stock icons.
        private static bool NotInFork(MethodBase m)
        {
            static bool Foreign(Type t) => t.Namespace == "System.Drawing.Imaging.Effects" || t.Name == "CachedBitmap"
                || t.Name == "StockIconId" || t.Name == "StockIconOptions";
            if (m is MethodInfo mi && Foreign(mi.ReturnType)) return true;
            return m.GetParameters().Any(p => Foreign(p.ParameterType.IsByRef ? p.ParameterType.GetElementType() : p.ParameterType));
        }

        private static bool Invokable(MethodBase m)
        {
            if (m.IsGenericMethodDefinition || NotInFork(m)) return false;
            if (m.GetCustomAttribute<ObsoleteAttribute>() is { IsError: true }) return false;
            foreach (ParameterInfo p in m.GetParameters())
            {
                Type t = p.ParameterType.IsByRef ? p.ParameterType.GetElementType() : p.ParameterType;
                if (t.IsPointer || t.IsByRefLike || t.IsGenericParameter)
                    return false;
            }
            return true;
        }

