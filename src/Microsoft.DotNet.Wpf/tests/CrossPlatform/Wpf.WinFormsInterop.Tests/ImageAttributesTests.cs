        // The output channel separates through the colour directory's rswop.icm (and the profile
        // cases name Windows' own profiles): elsewhere GDI+ itself would separate by mapping, and
        // there is no oracle for that.
        private static bool NeedsWindowsProfiles(string name)
            => name.Contains("channel") || name.StartsWith("profile/", StringComparison.Ordinal);

        [Fact]
        public void ImageAttributes_battery_is_GdiPlus_bytes()
        {
            var bad = new List<string>();
            int n = 0;
            foreach (KeyValuePair<string, string> kv in ImageAttributesBattery.Digests())
            {
                n++;
                if (Pending.Contains(kv.Key)) continue;
                if (!OperatingSystem.IsWindows() && NeedsWindowsProfiles(kv.Key)) continue;
                if (!GdiPlus.TryGetValue(kv.Key, out string want)) bad.Add(kv.Key + ": no fixture");
                else if (want != kv.Value) bad.Add(kv.Key);
            }
            Assert.Equal(GdiPlus.Count, n);
            Assert.True(bad.Count == 0, bad.Count + " of " + n + " differ from GDI+: " + string.Join(", ", bad));
        }
